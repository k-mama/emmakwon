#!/usr/bin/env node
// Regenerates migrations/0002_seed_published_posts.sql from
// src/content/studio-posts.json — the single source of truth for public
// content. Run this whenever studio-posts.json changes by hand (it is
// otherwise kept in sync automatically by the publishing pipeline).
//
// `--check` never writes. It fails when the committed recovery seed is
// stale, so CI can prevent a release whose D1 recovery copy no longer
// matches the public Studio JSON.
//
// The generated SQL is an idempotent upsert (ON CONFLICT(id) DO UPDATE):
// re-running it any number of times converges to the same published state,
// never duplicates rows, and never touches D1 rows for posts that don't
// exist in this JSON file (for example private drafts created in Admin).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const postsPath = path.join(root, "src/content/studio-posts.json");
const outPath = path.join(root, "migrations/0002_seed_published_posts.sql");
const checkOnly = process.argv.includes("--check");

const posts = JSON.parse(readFileSync(postsPath, "utf8"));

function sqlString(value) {
  if (value === undefined || value === null) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
  if (value === undefined || value === null) return "NULL";
  return sqlString(JSON.stringify(value));
}

const columns = [
  "id",
  "title",
  "slug",
  "excerpt",
  "cover_image",
  "body",
  "category",
  "tags",
  "status",
  "published_at",
  "scheduled_at",
  "created_at",
  "updated_at",
  "seo_title",
  "seo_description",
  "external_media",
];

const statements = posts.map((post) => {
  const values = [
    sqlString(post.id),
    sqlString(post.title),
    sqlString(post.slug),
    sqlString(post.excerpt),
    sqlString(post.coverImage),
    sqlJson(post.body),
    sqlString(post.category),
    sqlJson(post.tags ?? []),
    sqlString(post.status),
    sqlString(post.publishedAt),
    sqlString(post.scheduledAt),
    sqlString(post.createdAt),
    sqlString(post.updatedAt),
    sqlString(post.seoTitle),
    sqlString(post.seoDescription),
    sqlJson(post.externalMedia),
  ];

  const updateSet = columns
    .filter((column) => column !== "id" && column !== "created_at")
    .map((column) => `${column}=excluded.${column}`)
    .join(", ");

  return [
    `INSERT INTO studio_posts (${columns.join(", ")}, github_commit_sha, last_publish_error)`,
    `VALUES (${values.join(", ")}, NULL, NULL)`,
    `ON CONFLICT(id) DO UPDATE SET ${updateSet};`,
  ].join("\n");
});

const sql = `-- Auto-generated by scripts/generate-studio-seed.mjs from
-- src/content/studio-posts.json. Do not hand-edit — re-run the script.
--
-- Run:
--   npx wrangler d1 execute STUDIO_DB --local  --config wrangler.local.toml --file=migrations/0002_seed_published_posts.sql
--   npx wrangler d1 execute STUDIO_DB --remote --config wrangler.local.toml --file=migrations/0002_seed_published_posts.sql

${statements.join("\n\n")}\n`;

if (checkOnly) {
  const committed = readFileSync(outPath, "utf8");
  if (committed !== sql) {
    console.error("Studio recovery seed is stale. Run: node scripts/generate-studio-seed.mjs");
    process.exit(1);
  }
  console.log(`Studio recovery seed is current (${posts.length} published posts).`);
} else {
  writeFileSync(outPath, sql);
  console.log(`Wrote migrations/0002_seed_published_posts.sql (${posts.length} posts).`);
}
